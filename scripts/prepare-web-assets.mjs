#!/usr/bin/env node
/**
 * Generates the two web assets that must not be hand-maintained, into public/
 * before the web export, so they land in dist/ and get served from the site
 * root. Run by the Netlify build; run it locally with `npm run web:prepare`.
 *
 *   1. _redirects   — derived from the routes that actually exist in app/
 *   2. apple-app-site-association — derived from APPLE_TEAM_ID
 *   3. assetlinks.json — derived from ANDROID_CERT_SHA256
 *   4. _headers     — content types and hardening, for manual deploys
 *
 * ## _redirects
 *
 * Expo's static export writes a dynamic route as a literal file — thread/
 * [id].html — so a real URL like /thread/abc123 matches nothing on disk and
 * 404s. Every shared echo, profile and conversation link is a dynamic route,
 * so without a rewrite per route the links Echo puts into the world all break.
 *
 * The old file carried a comment saying "regenerate when a dynamic route is
 * added" with nothing to regenerate it, and it had drifted: /u and /c were
 * missing. Scanning app/ removes the opportunity to forget.
 *
 * ## apple-app-site-association
 *
 * Why this is generated rather than committed: the file must name the Apple
 * Team ID, and we do not have one — the Developer Program enrolment is still
 * pending. A committed file would have to carry a placeholder, and a
 * placeholder is worse than nothing here. Apple fetches this file through its
 * own CDN and caches the result; serving an AASA with an unresolvable app ID
 * teaches that CDN the association is invalid, and the cache outlives the fix.
 * A 404 teaches it nothing.
 *
 * So: no APPLE_TEAM_ID, no file. Set APPLE_TEAM_ID in the Netlify build
 * environment the day enrolment clears, redeploy, and universal links start
 * working with no app change.
 *
 * The path prefixes here must match the ones app.config.js claims for Android
 * and the ones parseEchoUniversalLink resolves. lib/publicHost.test.ts holds
 * those two together; this file is the third copy, and prepare-web-assets.test
 * .mjs checks it against them.
 */

import { mkdirSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const wellKnown = join(repoRoot, 'public', '.well-known');
const aasaPath = join(wellKnown, 'apple-app-site-association');

const appDir = join(repoRoot, 'app');
const redirectsPath = join(repoRoot, 'public', '_redirects');

/**
 * Every app/<segment>/[param].tsx becomes one rewrite. Status 200 rather than
 * 301 so the browser keeps the real URL and expo-router can read the id from
 * it on the client; a redirect would rewrite the address bar and lose it.
 */
function dynamicRouteRules() {
  const rules = [];
  for (const entry of readdirSync(appDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith('(') || entry.name.startsWith('+')) continue;
    for (const file of readdirSync(join(appDir, entry.name))) {
      if (!file.startsWith('[') || !file.endsWith('.tsx')) continue;
      const page = file.replace(/\.tsx$/, '.html');
      rules.push(`/${entry.name}/*    /${entry.name}/${page}    200`);
    }
  }
  return rules.sort();
}

function writeRedirects() {
  const rules = dynamicRouteRules();
  const body = [
    '# GENERATED by scripts/prepare-web-assets.mjs — do not edit by hand.',
    '# Rewrites for Echo\'s web build; one rule per dynamic route in app/.',
    '',
    ...rules,
    '',
    '# The root is the acquisition page, not the app shell. Forced (200!) so it',
    '# wins over dist/index.html, which the export writes for the app\'s own',
    '# index route.',
    '/    /download/index.html    200!',
    '',
    "# Anything else unknown falls through to Expo's own not-found page.",
    '/*    /+not-found.html    404',
    '',
  ].join('\n');
  writeFileSync(redirectsPath, body);
  console.log(`prepare-web-assets: wrote _redirects with ${rules.length} route rewrites`);
}

writeRedirects();

/**
 * netlify.toml carries these too, but it is only read for git-triggered
 * builds. A drag-and-drop deploy reads _headers from the uploaded folder, and
 * without it the association files are served as text/plain — which both
 * Apple's and Google's verifiers reject, silently, with no error anywhere.
 */
function writeHeaders() {
  const body = [
    '# GENERATED by scripts/prepare-web-assets.mjs — do not edit by hand.',
    '',
    '# Apple fetches this with no extension and requires JSON.',
    '/.well-known/apple-app-site-association',
    '  Content-Type: application/json',
    '',
    '/.well-known/assetlinks.json',
    '  Content-Type: application/json',
    '',
    '/*',
    '  X-Content-Type-Options: nosniff',
    '  X-Frame-Options: SAMEORIGIN',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '',
  ].join('\n');
  writeFileSync(join(repoRoot, 'public', '_headers'), body);
  console.log('prepare-web-assets: wrote _headers');
}

writeHeaders();

/** Apple Team IDs are exactly ten alphanumeric characters. */
const TEAM_ID_PATTERN = /^[A-Z0-9]{10}$/;

/** Must stay in step with app.config.js and lib/urlSafety.ts. */
const PATH_PREFIXES = ['/e', '/u', '/c'];

const assetlinksPath = join(wellKnown, 'assetlinks.json');

/** A SHA-256 certificate fingerprint: 32 hex byte pairs, colon separated. */
const CERT_SHA256_PATTERN = /^([0-9A-F]{2}:){31}[0-9A-F]{2}$/;

/**
 * Android App Links, from the certificate Google Play actually signs releases
 * with — read it from Play Console under Setup > App signing, as the SHA-256
 * of the *App signing key*, not the upload key.
 *
 * The committed version of this file used to carry the fingerprint of the
 * Android debug keystore, because that is what the release build was signed
 * with (android/app/build.gradle still points buildTypes.release at
 * signingConfigs.debug). Expo ships that same debug keystore to every project,
 * so publishing its fingerprint would have declared that *any* app signed with
 * the default debug key is a verified handler for our domain — not only ours.
 *
 * Absent beats wrong for the same reason as the AASA above: an unverifiable
 * declaration is a hole, and a missing one merely means links open the browser.
 */
function writeAssetLinks(pkg) {
  const fingerprint = (process.env.ANDROID_CERT_SHA256 || '').trim().toUpperCase();

  if (!fingerprint) {
    if (existsSync(assetlinksPath)) {
      rmSync(assetlinksPath);
      console.log('prepare-web-assets: ANDROID_CERT_SHA256 unset — removed stale assetlinks.json');
    } else {
      console.log('prepare-web-assets: ANDROID_CERT_SHA256 unset — skipping assetlinks.json (Android app links stay off)');
    }
    return;
  }

  if (!CERT_SHA256_PATTERN.test(fingerprint)) {
    console.error(`prepare-web-assets: ANDROID_CERT_SHA256 is not a colon-separated SHA-256 fingerprint`);
    process.exit(1);
  }

  mkdirSync(wellKnown, { recursive: true });
  writeFileSync(assetlinksPath, `${JSON.stringify([
    {
      relation: ['delegate_permission/common.handle_all_urls'],
      target: { namespace: 'android_app', package_name: pkg, sha256_cert_fingerprints: [fingerprint] },
    },
  ], null, 2)}\n`);
  console.log(`prepare-web-assets: wrote assetlinks.json for ${pkg}`);
}

const bundleId = 'com.downloadecho.echo';
const teamId = (process.env.APPLE_TEAM_ID || '').trim().toUpperCase();

writeAssetLinks(bundleId);

if (!teamId) {
  // Remove rather than leave: a file from an earlier build with a different
  // team ID would otherwise survive into this one.
  if (existsSync(aasaPath)) {
    rmSync(aasaPath);
    console.log('prepare-web-assets: APPLE_TEAM_ID unset — removed stale AASA');
  } else {
    console.log('prepare-web-assets: APPLE_TEAM_ID unset — skipping AASA (iOS universal links stay off)');
  }
  process.exit(0);
}

if (!TEAM_ID_PATTERN.test(teamId)) {
  console.error(`prepare-web-assets: APPLE_TEAM_ID "${teamId}" is not a 10-character Apple Team ID`);
  process.exit(1);
}

const appId = `${teamId}.${bundleId}`;

const aasa = {
  applinks: {
    apps: [],
    details: [
      {
        appIDs: [appId],
        components: PATH_PREFIXES.map(prefix => ({ '/': `${prefix}/*` })),
      },
    ],
  },
  webcredentials: { apps: [appId] },
};

mkdirSync(wellKnown, { recursive: true });
writeFileSync(aasaPath, `${JSON.stringify(aasa, null, 2)}\n`);
console.log(`prepare-web-assets: wrote AASA for ${appId}`);
