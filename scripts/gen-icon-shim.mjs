// Regenerates lib/core/phosphorShim.js: the only Phosphor icons the app ships.
//
// metro.config.js points 'phosphor-react-native' at that file. The package's own barrel pulls in all
// 1,512 icons (about 3 MB of Hermes bytecode, 22% of the bundle); the app uses a few hundred.
// Run after adding or removing an icon import:  node scripts/gen-icon-shim.mjs
import { readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function buildShim() {
const iconDir = join(root, 'node_modules/phosphor-react-native/lib/commonjs/icons');
const files = new Set(readdirSync(iconDir).filter((f) => f.endsWith('.js')).map((f) => f.slice(0, -3)));

const dirs = ['app', 'components', 'hooks', 'lib', 'store', 'constants', 'test'];
const sources = [];
const walk = (d) => {
  for (const name of readdirSync(d)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const p = join(d, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx|js|jsx)$/.test(name) && !p.endsWith('lib/core/phosphorShim.js')) sources.push(p);
  }
};
for (const d of dirs) { try { walk(join(root, d)); } catch { /* optional dir */ } }

const used = new Set();
const importRe = /import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"]phosphor-react-native['"]/g;
for (const f of sources) {
  const s = readFileSync(f, 'utf8');
  for (const m of s.matchAll(importRe)) {
    for (const part of m[1].split(',')) {
      const item = part.trim();
      if (!item || item.startsWith('type ')) continue;
      used.add(item.split(/\s+as\s+/)[0].trim());
    }
  }
}

// Erased at build time (imported without the `type` keyword); nothing to ship.
const TYPES = new Set(['Icon', 'IconProps', 'IconWeight']);
const lines = [];
const unknown = [];
for (const name of [...used].sort()) {
  if (TYPES.has(name)) { used.delete(name); continue; }
  const file = files.has(name) ? name : name.endsWith('Icon') && files.has(name.slice(0, -4)) ? name.slice(0, -4) : null;
  if (!file) { unknown.push(name); continue; }
  lines.push(`export { ${name} } from '../../node_modules/phosphor-react-native/lib/commonjs/icons/${file}';`);
}
if (unknown.length) throw new Error('Not Phosphor icons: ' + unknown.join(', '));

  return {
    count: used.size,
    text:
      `// GENERATED by scripts/gen-icon-shim.mjs. Do not edit by hand.\n` +
      `// ${used.size} icons: only those the app imports. See the generator for why.\n` +
      `/* eslint-disable */\n${lines.join('\n')}\n`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { text, count } = buildShim();
  writeFileSync(join(root, 'lib/core/phosphorShim.js'), text);
  console.log(`wrote lib/core/phosphorShim.js with ${count} icons`);
}
